import AppKit
import ImageIO
import UniformTypeIdentifiers

struct ClipboardImagePayload {
    let png: Data
    let tiff: Data
    init?(data: Data) {
        guard let image = NSImage(data: data), let tiff = image.tiffRepresentation,
              let bitmap = NSBitmapImageRep(data: tiff) else { return nil }
        let source = CGImageSourceCreateWithData(data as CFData, nil)
        let isPNG = source.flatMap { CGImageSourceGetType($0) }.map { ($0 as String) == UTType.png.identifier } ?? false
        guard let png = isPNG ? data : bitmap.representation(using: .png, properties: [:]) else { return nil }
        self.png = png; self.tiff = tiff
    }
    func item(fileURL: URL?) -> NSPasteboardItem {
        let item = NSPasteboardItem()
        item.setData(png, forType: .png); item.setData(tiff, forType: .tiff)
        if let fileURL {
            item.setString(fileURL.absoluteString, forType: .fileURL)
        }
        return item
    }
}

enum ImagePasteCompatibility {
    static func isWeChat(_ bundleID: String?) -> Bool {
        let id = bundleID?.lowercased() ?? ""
        return id.hasPrefix("com.tencent.xinwechat") || id == "com.tencent.wechat"
    }
}

enum ImageFilePreview {
    static let byteLimit = 20 * 1024 * 1024
    static func load(from text: String) -> Data? {
        let paths = text.components(separatedBy: "\n")
        guard paths.count == 1, let url = URL(string: paths[0]), url.isFileURL,
              let type = UTType(filenameExtension: url.pathExtension), type.conforms(to: .image),
              let values = try? url.resourceValues(forKeys: [.isRegularFileKey, .fileSizeKey]), values.isRegularFile == true,
              let size = values.fileSize, size > 0, size <= byteLimit,
              let data = try? Data(contentsOf: url, options: .mappedIfSafe), data.count <= byteLimit,
              let source = CGImageSourceCreateWithData(data as CFData, [kCGImageSourceShouldCache: false] as CFDictionary), CGImageSourceGetCount(source) > 0 else { return nil }
        return data
    }
}

final class ClipboardService {
    private let pasteboard: NSPasteboard
    private var lastChange: Int
    private var timer: Timer?
    private let store: ClipStore
    private let preferences: Preferences
    private let source: () -> (String, String)
    init(store: ClipStore, preferences: Preferences = .shared, pasteboard: NSPasteboard = .general, source: @escaping () -> (String, String) = {
        let app = NSWorkspace.shared.frontmostApplication
        return (app?.localizedName ?? "未知应用", app?.bundleIdentifier ?? "")
    }) {
        self.store = store; self.preferences = preferences; self.pasteboard = pasteboard; self.source = source
        lastChange = pasteboard.changeCount
    }
    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.55, repeats: true) { [weak self] _ in self?.poll() }
        if let timer { RunLoop.main.add(timer, forMode: .common) }
    }
    func stop() { timer?.invalidate(); timer = nil }
    func poll() {
        guard pasteboard.changeCount != lastChange else { return }
        lastChange = pasteboard.changeCount
        guard !preferences.paused else { return }
        let (app, bundle) = source()
        guard !preferences.excluded.contains(bundle) else { return }
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        let privateTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
        guard types.isDisjoint(with: privateTypes) else { return }
        let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL] ?? []
        let clip: Clip
        if urls.count > 1 {
            clip = .make(kind: .files, text: urls.map(\.absoluteString).joined(separator: "\n"), source: app, bundleID: bundle)
        } else if let data = imageData() {
            clip = .make(kind: .image, text: "图片", data: data, source: app, bundleID: bundle)
        } else if !urls.isEmpty {
            clip = .make(kind: .files, text: urls.map(\.absoluteString).joined(separator: "\n"), source: app, bundleID: bundle)
        } else if let text = pasteboard.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, text.utf8.count <= 1024 * 1024 {
            let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
            let url = URL(string: trimmed)
            let isLink = !trimmed.contains(where: { $0.isWhitespace }) && ["http", "https"].contains(url?.scheme?.lowercased() ?? "") && url?.host != nil
            clip = .make(kind: isLink ? .link : .text, text: text, source: app, bundleID: bundle)
        } else { return }
        store.insert(clip, limit: preferences.limit)
        if clip.kind == .files { store.loadFilePreviews(retrying: clip.id) }
    }
    private func imageData() -> Data? {
        for type in [NSPasteboard.PasteboardType.png, .tiff, .init("public.jpeg"), .init("public.heic")] {
            if let data = pasteboard.data(forType: type), data.count <= ImageFilePreview.byteLimit, NSImage(data: data) != nil { return data }
        }
        return nil
    }
    @discardableResult func copy(_ clip: Clip) -> Bool {
        let objects: [NSPasteboardWriting]
        switch clip.kind {
        case .image:
            guard let data = clip.data, let payload = ClipboardImagePayload(data: data) else { return false }
            objects = [payload.item(fileURL: nil)]
        case .files:
            let urls = clip.text.components(separatedBy: "\n").compactMap { URL(string: $0) }.filter(\.isFileURL)
            guard !urls.isEmpty else { return false }
            if urls.count == 1, let data = clip.data, let payload = ClipboardImagePayload(data: data) {
                let original = urls.first.flatMap { FileManager.default.fileExists(atPath: $0.path) ? $0 : nil }
                objects = [payload.item(fileURL: original)]
            } else { objects = urls.map { $0 as NSURL } }
        case .text, .link:
            let item = NSPasteboardItem(); item.setString(clip.text, forType: .string); objects = [item]
        }
        pasteboard.clearContents()
        let result = pasteboard.writeObjects(objects)
        lastChange = pasteboard.changeCount
        return result
    }
}
